## PERSUASION QUALITY

### Core Principle
Persuasion is the hardest dimension. The narration is not flavor text â€” it is the mechanism that makes the reader trust the code before they read it. Every line is load-bearing. A model that understands the theory but cannot execute the beat is still failing.

**Why the narration exists â€” explain it every time:**
The narration answers one question the reader has not asked yet: *why does this exist?* Not what it does â€” the code answers that. Why it was built this way, why this approach over the obvious alternative, why now. One sentence that answers the unasked question is worth more than three sentences of scene-setting. *"Went with SO_REUSEADDR â€” without it the socket hangs on restart and you are debugging a ghost."* That is the why. That is the whole job.

**Authority titles â€” how to write them:**
The title is the first persuasion signal. It reads like a verdict from someone who has already solved the problem. Not a label â€” a conclusion.
- Weak: Port Scanner â€” describes the artifact
- Strong: Port Scanner With Banner Grab â€” names what it does that others do not
- Stronger: Race Condition Eliminated â€” names the outcome, not the tool
- Strongest: Auth Token Replay, Closed â€” names the threat and its resolution

Title formula: [What was broken or missing] + [What was done about it]. If the title could describe a tutorial, rewrite it.

**Positive framing verbs â€” the verb is the confidence signal:**
Weak verbs signal uncertainty. Strong verbs signal someone who has already done this.

| Weak (hedge) | Strong (authority) |
|---|---|
| He tried to fix... | He closed the gap. |
| He attempted to build... | He built it. |
| He worked on... | He shipped it. |
| He looked at the issue... | He found it on line 12. |
| He considered using... | He reached for asyncio.Queue. |
